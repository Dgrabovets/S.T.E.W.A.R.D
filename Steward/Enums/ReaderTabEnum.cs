namespace Steward.Models;

/// <summary>
/// Вкладка читалки расшифровки: разделы разбора занятия, между которыми не нужно листать
/// </summary>
public enum ReaderTabEnum
{
    /// <summary>
    /// Где в расшифровке сказано задание: цитата и строки вокруг неё. Появляется, когда расшифровка открыта из карточки задания
    /// </summary>
    Quote,

    /// <summary>
    /// Что пройдено и что было на занятии
    /// </summary>
    Covered,

    /// <summary>
    /// Задания занятия: слова преподавателя с репликами вокруг них. Есть, только если на занятии давали задания
    /// </summary>
    Assignments,

    /// <summary>
    /// Темы и формулировки преподавателя
    /// </summary>
    Topics,

    /// <summary>
    /// Принятые решения и задачи с занятия
    /// </summary>
    Actions,

    /// <summary>
    /// Кто сколько говорил
    /// </summary>
    Speakers,
}
