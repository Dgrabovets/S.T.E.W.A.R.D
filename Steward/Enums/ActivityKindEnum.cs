namespace Steward.Models;

/// <summary>
/// Как выглядит и движется сфера из точек. Первые пять видов показывают процесс, остальные постоянное состояние задачи
/// </summary>
public enum ActivityKindEnum
{
    /// <summary>
    /// Равномерное вращение: любая работа
    /// </summary>
    Working,

    /// <summary>
    /// По сфере сверху вниз проходит светлая полоса: поиск в тексте
    /// </summary>
    Searching,

    /// <summary>
    /// Точки волной стягиваются к центру и расходятся: связь с почтой и ботом
    /// </summary>
    Connecting,

    /// <summary>
    /// Точки слетаются из пространства и собираются в сферу: подготовка документа
    /// </summary>
    Composing,

    /// <summary>
    /// Сфера медленно сжимается и расширяется: ожидание
    /// </summary>
    Breathing,

    /// <summary>
    /// Плотная сфера с лёгким мерцанием: задача работает
    /// </summary>
    Alive,

    /// <summary>
    /// Спокойная сфера, почти не вращается: задача выполнена
    /// </summary>
    Calm,

    /// <summary>
    /// Редкие тусклые точки: задача отключена
    /// </summary>
    Dormant,

    /// <summary>
    /// Частое «дыхание»: задача ждёт решения человека
    /// </summary>
    Attention,

    /// <summary>
    /// Рассыпающаяся сфера: задача не удалась
    /// </summary>
    Failed,

    /// <summary>
    /// Сфера с поясом из быстрых ярких точек: общий статус рядом с заголовком
    /// </summary>
    Beacon,

    /// <summary>
    /// Редкая сфера, которая очень медленно «дышит»: задача выполнена и ждёт своего следующего срока
    /// </summary>
    Waiting,

    /// <summary>
    /// Глобус из широт, почти неподвижный: запуск закончился успешно
    /// </summary>
    Sealed,

    /// <summary>
    /// Сфера, от которой отрываются и уплывают осколки: запуск закончился ошибкой
    /// </summary>
    Shattered,

    /// <summary>
    /// Неподвижная сфера, по которой кругом идёт яркий луч, как стрелка часов: запуск не уложился во время
    /// </summary>
    Sweep,

    /// <summary>
    /// Одно кольцо из точек без самой сферы: запуск не состоялся
    /// </summary>
    Hollow,
}