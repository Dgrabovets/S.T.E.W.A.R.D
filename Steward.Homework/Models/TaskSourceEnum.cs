namespace Steward.Homework.Models;

/// <summary>
/// Откуда у предмета берутся домашние задания. Числовые значения записаны в файл настроек предмета, поэтому их порядок менять нельзя
/// </summary>
public enum TaskSourceEnum
{
    /// <summary>
    /// Программа решает сама: если в LMS у предмета есть работы с текстом условия, задания там, иначе их даёт преподаватель на занятии
    /// </summary>
    Auto = 0,

    /// <summary>
    /// Задания лежат в LMS (текстом или файлами): из расшифровок они не берутся, карточки строятся по работам LMS без обращения к агенту
    /// </summary>
    Lms = 1,

    /// <summary>
    /// Преподаватель даёт задания на занятии: их ищет в расшифровке агент
    /// </summary>
    Transcript = 2,
}
