namespace Steward.Homework.Models;

/// <summary>
/// Что делать с занятием: забирать ли его расшифровку
/// </summary>
public enum LessonStateEnum
{
    /// <summary>
    /// Выбор ещё не сделан: расшифровку не забираем, занятие ждёт решения
    /// </summary>
    Undecided,

    /// <summary>
    /// Забрать расшифровку и подготовить задания
    /// </summary>
    Fetch,

    /// <summary>
    /// Занятие не нужно: пробная запись, чужая группа или предмет без заданий
    /// </summary>
    Skip,

    /// <summary>
    /// Задания по занятию уже сделаны: расшифровку не забираем
    /// </summary>
    Done,

    /// <summary>
    /// Забрать расшифровку и разобрать занятие, а домашние задания не готовить: предмет без заданий или задания не нужны
    /// </summary>
    Analyze = 4,

    /// <summary>
    /// Только задания из LMS: расшифровку не забираем и занятие не разбираем, задания копируются из LMS и готовятся. Для предмета, у которого всё лежит на сайте
    /// </summary>
    LmsOnly = 5,
}
